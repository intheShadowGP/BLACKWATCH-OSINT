import type { QueryType } from '@/types';

export type L10n = { fr: string; en: string };

export const SOURCE_CATEGORIES = [
  'search-engines',
  'dns',
  'ip-intelligence',
  'domain-intelligence',
  'geoint',
  'social-media',
  'public-records',
  'image-analysis',
  'email-intelligence',
  'open-data',
] as const;
export type SourceCategory = (typeof SOURCE_CATEGORIES)[number];

/**
 * - api:    queried automatically from the browser (CORS verified)
 * - link:   cannot be queried from a browser (CORS / ToS / auth) — BLACKWATCH
 *           builds the official URL and the analyst records the outcome manually
 * - local:  runs entirely in the browser, sends nothing
 */
export type AccessType = 'api' | 'link' | 'local';
export type SourceMode = 'auto' | 'manual' | 'off';

export interface SourceDefinition {
  id: string;
  name: string;
  category: SourceCategory;
  homepage: string;
  docsUrl?: string;
  privacyUrl?: string;
  termsUrl?: string;
  description: L10n;
  access: AccessType;
  requiresKey: boolean;
  /** Result of a real browser fetch from a localhost origin. */
  cors: 'yes' | 'no' | 'n/a';
  quota: L10n;
  /** What leaves the browser when this source is queried. */
  sentData: L10n;
  purpose: L10n;
  /** Hosts contacted (feeds the CSP connect-src). */
  hosts: string[];
  /** ISO date of the last real browser test; undefined = not verified. */
  lastVerified?: string;
  defaultMode: SourceMode;
  minIntervalMs: number;
  maxPerHour: number;
  queryTypes: QueryType[];
}

const VERIFIED = '2026-11-12';

const L = (fr: string, en: string): L10n => ({ fr, en });

const SENT_DOMAIN = L('Le nom de domaine recherché, votre adresse IP, l’heure de la requête.', 'The searched domain name, your IP address, the request time.');
const SENT_IP = L('L’adresse IP recherchée, votre adresse IP, l’heure de la requête.', 'The searched IP address, your IP address, the request time.');
const SENT_USERNAME = L('Le pseudonyme recherché, votre adresse IP, l’heure de la requête.', 'The searched username, your IP address, the request time.');
const SENT_KEYWORD = L('Les termes recherchés, votre adresse IP, l’heure de la requête.', 'The search terms, your IP address, the request time.');
const SENT_NONE = L('Rien : lien ouvert manuellement par l’analyste.', 'Nothing: the analyst opens the link manually.');
const MANUAL_QUOTA = L('Soumis aux conditions de la plateforme. Consultation manuelle uniquement.', 'Subject to the platform terms. Manual consultation only.');

function api(def: Omit<SourceDefinition, 'access' | 'requiresKey' | 'cors' | 'lastVerified'> & Partial<SourceDefinition>): SourceDefinition {
  return { access: 'api', requiresKey: false, cors: 'yes', lastVerified: VERIFIED, ...def };
}

function link(def: {
  id: string;
  name: string;
  category: SourceCategory;
  homepage: string;
  description: L10n;
  queryTypes: QueryType[];
  privacyUrl?: string;
  termsUrl?: string;
  reason: L10n;
}): SourceDefinition {
  return {
    id: def.id,
    name: def.name,
    category: def.category,
    homepage: def.homepage,
    privacyUrl: def.privacyUrl,
    termsUrl: def.termsUrl,
    description: def.description,
    access: 'link',
    requiresKey: false,
    cors: 'no',
    quota: MANUAL_QUOTA,
    sentData: SENT_NONE,
    purpose: def.reason,
    hosts: [],
    defaultMode: 'manual',
    minIntervalMs: 0,
    maxPerHour: 0,
    queryTypes: def.queryTypes,
  };
}

